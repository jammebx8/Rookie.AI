/**
 * Dropper · token build. `npm run tokens`
 * Reads dropper/tokens/tokens.ts → writes tokens.css (variables) + theme.css (Tailwind v4 @theme).
 * Node ≥ 22.18 / 23.6 runs this .ts file directly (type stripping).
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  palette, semantic, gradients, spacing, radius, font, type, shadow, motion, z, layout,
} from '../tokens/tokens.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'tokens');
const HEADER = '/* ⚠️ GENERATED by dropper/scripts/build-tokens.ts from dropper/tokens/tokens.ts — do not edit by hand. Run `npm run tokens`. */\n';

const lines: string[] = [];
const push = (s = '') => lines.push(s);

/* ── tokens.css ─────────────────────────────────────────────────────────── */
push(HEADER);
push('/* Dropper Design System — CSS custom properties. Primitives + light semantics on :root; dark semantics on .dark. */');
push(':root {');
push('  /* palette */');
for (const [fam, steps] of Object.entries(palette)) {
  for (const [step, hex] of Object.entries(steps)) push(`  --dp-${fam}-${step}: ${hex};`);
}
push('\n  /* semantic · light */');
for (const [group, tokensOf] of Object.entries(semantic)) {
  for (const [name, pair] of Object.entries(tokensOf)) push(`  --dp-${group}-${name}: ${pair.light};`);
}
push('\n  /* gradients */');
for (const [k, v] of Object.entries(gradients)) push(`  --dp-gradient-${k}: ${v};`);
push('\n  /* spacing (named) */');
for (const [k, v] of Object.entries(spacing)) push(`  --dp-space-${k}: ${v.value};`);
push('\n  /* radius */');
for (const [k, v] of Object.entries(radius)) push(`  --dp-radius-${k}: ${v.value};`);
push('\n  /* type */');
push(`  --dp-font-sans: ${font.sans};`);
push(`  --dp-font-mono: ${font.mono};`);
push(`  --dp-font-exam: ${font.serifExam};`);
for (const [k, v] of Object.entries(type)) {
  push(`  --dp-text-${k}: ${v.size};`);
  push(`  --dp-text-${k}-line: ${v.line};`);
  push(`  --dp-text-${k}-track: ${v.track};`);
  push(`  --dp-text-${k}-weight: ${v.weight};`);
}
push('\n  /* elevation */');
for (const [k, v] of Object.entries(shadow)) push(`  --dp-shadow-${k}: ${v.value};`);
push('\n  /* motion */');
for (const [k, v] of Object.entries(motion.duration)) push(`  --dp-duration-${k}: ${v};`);
for (const [k, v] of Object.entries(motion.ease)) push(`  --dp-ease-${k}: ${v.value};`);
push('\n  /* layers & layout */');
for (const [k, v] of Object.entries(z)) push(`  --dp-z-${k}: ${v};`);
for (const [k, v] of Object.entries(layout)) push(`  --dp-layout-${k}: ${v.value};`);

push('\n  /* legacy aliases (landing page, pre-Dropper code). Prefer --dp-*. */');
for (const fam of ['sky', 'clay', 'marigold', 'mint'] as const) {
  for (const step of Object.keys(palette[fam])) push(`  --rk-${fam}-${step}: var(--dp-${fam}-${step});`);
}
const rkInk: Record<string, string> = {
  0: palette.gray[0], 25: palette.paper[25], 50: palette.paper[50], 100: palette.paper[100], 300: palette.gray[300],
  500: palette.gray[500], 700: palette.gray[700], 900: palette.gray[900], 950: palette.gray[950],
};
for (const [k, v] of Object.entries(rkInk)) push(`  --rk-ink-${k}: ${v};`);
for (const k of [900, 800, 700, 400, 200, 50] as const) push(`  --rk-night-${k}: var(--dp-night-${k});`);
push('}');
push('');
push('/* semantic · dark ("Night owl") */');
push(".dark, [data-theme='dark'] {");
for (const [group, tokensOf] of Object.entries(semantic)) {
  for (const [name, pair] of Object.entries(tokensOf)) push(`  --dp-${group}-${name}: ${pair.dark};`);
}
push('}');
writeFileSync(join(out, 'tokens.css'), lines.join('\n') + '\n');

/* ── theme.css (Tailwind v4) ────────────────────────────────────────────── */
const t: string[] = [];
const tp = (s = '') => t.push(s);
tp(HEADER);
tp('/* Dropper → Tailwind v4 utilities. Imported once from app/globals.css (after tailwindcss). */');
tp('@theme inline {');
tp('  /* palette: bg-dp-sky-300, text-dp-red-500 … (use semantics first) */');
for (const [fam, steps] of Object.entries(palette)) {
  for (const step of Object.keys(steps)) tp(`  --color-dp-${fam}-${step}: var(--dp-${fam}-${step});`);
}
const sem: Record<string, string> = {
  canvas: 'surface-canvas', base: 'surface-base', surface: 'surface-card', raised: 'surface-raised', sunken: 'surface-sunken', inverse: 'surface-inverse',
  fg: 'text-primary', 'fg-secondary': 'text-secondary', 'fg-muted': 'text-muted', 'fg-inverse': 'text-inverse', link: 'text-link',
  line: 'border-default', 'line-subtle': 'border-subtle', 'line-strong': 'border-strong', focus: 'border-focus',
  'action-primary': 'action-primary', 'action-primary-hover': 'action-primary-hover', 'on-primary': 'action-on-primary',
  'action-secondary': 'action-secondary', 'action-secondary-hover': 'action-secondary-hover', 'on-secondary': 'action-on-secondary',
  'action-neutral': 'action-neutral', 'action-neutral-hover': 'action-neutral-hover',
  success: 'feedback-success', 'success-surface': 'feedback-success-surface', 'success-border': 'feedback-success-border',
  danger: 'feedback-danger', 'danger-surface': 'feedback-danger-surface', 'danger-border': 'feedback-danger-border', 'danger-text': 'feedback-danger-text',
  warning: 'feedback-warning', 'warning-surface': 'feedback-warning-surface', 'warning-text': 'feedback-warning-text',
};
tp('\n  /* semantic colours: bg-canvas, bg-surface, text-fg-muted, ring-line, bg-success-surface … */');
for (const [k, v] of Object.entries(sem)) tp(`  --color-${k}: var(--dp-${v});`);
tp('\n  /* radius: rounded-tag | rounded-control | rounded-card | rounded-round */');
for (const k of Object.keys(radius)) tp(`  --radius-${k}: var(--dp-radius-${k});`);
tp('\n  /* spacing: p-card, gap-stack, mt-section, px-gutter … (numeric p-1…p-24 = 4pt grid) */');
for (const k of Object.keys(spacing)) tp(`  --spacing-${k}: var(--dp-space-${k});`);
tp('\n  /* type: text-display | text-value | text-heading | text-title | text-body-lg | text-body | text-body-sm | text-label | text-meta | text-caption | text-price */');
tp('  --font-sans: var(--dp-font-sans);');
tp('  --font-mono: var(--dp-font-mono);');
tp('  --font-exam: var(--dp-font-exam);');
for (const k of Object.keys(type)) {
  tp(`  --text-${k}: var(--dp-text-${k});`);
  tp(`  --text-${k}--line-height: var(--dp-text-${k}-line);`);
  tp(`  --text-${k}--letter-spacing: var(--dp-text-${k}-track);`);
  tp(`  --text-${k}--font-weight: var(--dp-text-${k}-weight);`);
}
tp('\n  /* elevation: shadow-hover | shadow-raised | shadow-float | shadow-sale */');
for (const k of Object.keys(shadow)) if (k !== 'none') tp(`  --shadow-${k}: var(--dp-shadow-${k});`);
tp('\n  /* motion: ease-standard | ease-emphasized | ease-exit */');
for (const k of Object.keys(motion.ease)) tp(`  --ease-${k}: var(--dp-ease-${k});`);
tp('\n  /* layout: max-w-content | max-w-focus | max-w-prose */');
tp('  --container-content: var(--dp-layout-content);');
tp('  --container-focus: var(--dp-layout-focus);');
tp('  --container-prose: var(--dp-layout-prose);');
tp('}');
writeFileSync(join(out, 'theme.css'), t.join('\n') + '\n');

console.log('Dropper tokens → dropper/tokens/tokens.css, dropper/tokens/theme.css');
